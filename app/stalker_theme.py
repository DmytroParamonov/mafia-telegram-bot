DEATH_RE = re.compile(
    r"☀️ <b>Город просыпается</b>\n\n💀 Этой ночью погиб <b>(.*?)</b>\.(.*)",
    re.DOTALL,
)


def stalkerize_text(text: str) -> str:
    death_match = DEATH_RE.fullmatch(text)
    if death_match:
        name, suffix = death_match.groups()
        suffix = suffix.replace("\nЕго роль:", "\nРоль:").replace("Неизвестно", "Невідомо")
        for source, target in TEXT_REPLACEMENTS:
            suffix = suffix.replace(source, target)
        return night_death_text(name, suffix)

    if text == (
        "☀️ <b>Город просыпается</b>\n\n"
        "🩺 Этой ночью было покушение, но жертва выжила. Доктор попал точно в цель."
    ):
        return saved_text()

    if text == "☀️ <b>Город просыпается</b>\n\nЭтой ночью никто не погиб.":
        return quiet_night_text()

    for source, target in TEXT_REPLACEMENTS:
        text = text.replace(source, target)
    return text


def stalkerize_button(text: str) -> str:
    for source, target in BUTTON_REPLACEMENTS:
        text = text.replace(source, target)
    return text


def stalkerize_markup(markup: InlineKeyboardMarkup) -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(
        inline_keyboard=[
            [button.model_copy(update={"text": stalkerize_button(button.text)}) for button in row]
            for row in markup.inline_keyboard
        ]
    )


class StalkerBot(Bot):
    """Ukrainian STALKER presentation adapter over the stable game engine."""

    async def __call__(
        self,
        method: Any,
        request_timeout: int | None = None,
    ) -> Any:
        updates: dict[str, Any] = {}
        text = getattr(method, "text", None)
        if isinstance(text, str):
            updates["text"] = stalkerize_text(text)

        reply_markup = getattr(method, "reply_markup", None)
        if isinstance(reply_markup, InlineKeyboardMarkup):
            updates["reply_markup"] = stalkerize_markup(reply_markup)

        if updates and hasattr(method, "model_copy"):
            method = method.model_copy(update=updates)

        return await super().__call__(method, request_timeout=request_timeout)
